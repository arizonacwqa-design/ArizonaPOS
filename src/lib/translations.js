export function useTranslation() {
  const language = useLanguageStore((s) => s.language);
  const t = (key) => {
    return translations[language]?.[key] || translations['en']?.[key] || key;
  };
  const isRtl = language === 'ar';
  return { t, language, isRtl };
}
